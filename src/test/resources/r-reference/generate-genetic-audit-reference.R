lse <- function(x) { m <- max(x); if(!is.finite(m)) return(m); m+log(sum(exp(x-m))) }
coloc_ref <- function(a,b,w1=rep(1,length(a)),w2=rep(1,length(b))) {
  n <- length(a); p1 <- 1e-4; p2 <- 1e-4; p12 <- 5e-6
  x <- a+log(n*p1)+log(w1)-lse(log(w1))
  y <- b+log(n*p2)+log(w2)-lse(log(w2))
  joint <- outer(x,y,'+')
  h <- c(0,lse(x),lse(y),lse(joint[row(joint)!=col(joint)]),
         log(p12)-log(p1)-log(p2)+lse(diag(joint)))
  shared <- diag(joint); z <- lse(shared)
  c(exp(h-lse(h)),if(is.finite(z))exp(shared-z) else rep(0,n))
}
ser <- function(z,n=400,V=.2) {
  df <- n-1; xty <- df*z/sqrt(z*z+n-2); se2 <- 1/df
  shrink <- V/(V+se2); mu <- shrink*xty/df
  bf <- .5*(log(se2/(se2+V))+(xty/df)^2*V/(se2*(se2+V)))
  alpha <- exp(bf-lse(bf)); c(alpha,alpha*mu,bf)
}
winner <- function(t,c) {
  # Independent Brent root solver for the exact conditional likelihood score.
  # Direct optimize(logLik) loses ~3e-7 here because the likelihood is flat.
  score <- function(mu) {
    logp <- lse(c(pnorm(c-mu,lower.tail=FALSE,log.p=TRUE),pnorm(c+mu,lower.tail=FALSE,log.p=TRUE)))
    t-mu-exp(dnorm(c-mu,log=TRUE)-logp)+exp(dnorm(c+mu,log=TRUE)-logp)
  }
  uniroot(score,c(0,t),tol=1e-12)$root
}
