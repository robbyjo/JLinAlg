timing <- function(label,f,reps=200L) {
  for(i in seq_len(30)) f()
  times <- numeric(5); checksum <- 0
  for(batch in seq_len(5)) {
    elapsed <- system.time(for(i in seq_len(reps)) { value <- f(); checksum <- checksum+sum(value^2*seq_along(value)) })[['elapsed']]
    times[batch] <- elapsed*1000/reps
  }
  cat(sprintf('%s median_ms=%.9g checksum=%.17g calls=%d\n',label,median(times),checksum,5L*reps))
}
