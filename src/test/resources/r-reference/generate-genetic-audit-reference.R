mixture_ll <- function(beta,pi) {
  r <- c(-400,0,400)-beta; v <- 1+beta^2*1e-12
  sum(vapply(r,function(x)lse(c(log(pi)+dnorm(x,sd=sqrt(v),log=TRUE),log1p(-pi)+dnorm(x,sd=sqrt(v+.01),log=TRUE))),0.0))
}
