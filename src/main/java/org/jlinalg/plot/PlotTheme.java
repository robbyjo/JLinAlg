package org.jlinalg.plot;

/** Built-in presentation themes. */
public enum PlotTheme {
    /** Neutral defaults with a white plotting surface. */
    DEFAULT,
    /** Grey-panel styling familiar to ggplot2 users. */
    GGPLOT2,
    /** Sparse white styling with subtle grid lines. */
    MINIMAL,
    /** Axis-focused styling without plot grid lines. */
    CLASSIC
}
